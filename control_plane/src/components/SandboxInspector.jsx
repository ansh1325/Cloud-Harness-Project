import React, { useEffect, useRef, useState } from 'react';

function classifyTerminalLine(line) {
  const trimmed = line.trim();
  if (!trimmed || /^[=\-_]{10,}$/.test(trimmed)) return null;
  if (trimmed.startsWith('[PHASE 2') && trimmed.includes('PASSED')) return 'term-line term-phase-pass';
  if (trimmed.startsWith('[PHASE ')) return 'term-line term-phase';
  if (/\bPASSED\b/.test(line) || (/\d+ passed/.test(line) && !/failed/.test(line))) return 'term-line term-pass';
  if (/\bFAILED\b|Error:|AssertionError|KeyError|ZeroDivisionError/.test(line)) return 'term-line term-fail';
  if (trimmed.startsWith('collecting') || trimmed.startsWith('collected') || trimmed.startsWith('[STREAM')) {
    return 'term-line term-meta';
  }
  return 'term-line';
}

export default function SandboxInspector({
  activeTab,
  onTabChange,
  selectedTaskId,
  isResolved,
  baselineLines,
  verifyLines,
  diffText,
  diffStats,
  prPayload
}) {
  const termRef = useRef(null);
  const [copied, setCopied] = useState(false);
  const [showBefore, setShowBefore] = useState(true);

  // Auto-collapse Phase 1 ("Before Fix") once Phase 2 passes so user sees the green verification cleanly
  useEffect(() => {
    if (isResolved) {
      setShowBefore(false);
    } else {
      setShowBefore(true);
    }
  }, [isResolved, selectedTaskId]);

  useEffect(() => {
    if (activeTab === 'terminal' && termRef.current) {
      termRef.current.scrollTop = termRef.current.scrollHeight;
    }
  }, [baselineLines.length, verifyLines.length, activeTab]);

  const handleCopyDiff = async () => {
    if (!diffText) return;
    try {
      await navigator.clipboard.writeText(diffText);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    } catch {
      // Clipboard blocked in non-HTTPS contexts
    }
  };

  return (
    <div className="panel">
      <div className="tabs">
        <div className="tab-group">
          <div
            className={`tab ${activeTab === 'diff' ? 'active' : ''}`}
            onClick={() => onTabChange('diff')}
          >
            Generated Changes
            {diffStats && (diffStats.insertions > 0 || diffStats.deletions > 0) && (
              <span className="tab-badge">
                +{diffStats.insertions}/-{diffStats.deletions}
              </span>
            )}
          </div>
          <div
            className={`tab ${activeTab === 'terminal' ? 'active' : ''}`}
            onClick={() => onTabChange('terminal')}
          >
            Before / After Tests
          </div>
          <div
            className={`tab ${activeTab === 'pr' ? 'active' : ''}`}
            onClick={() => onTabChange('pr')}
          >
            PR Payload
          </div>
        </div>

        {diffText && selectedTaskId && (
          <div style={{ display: 'flex', gap: 6 }}>
            <button className="btn-ghost" onClick={handleCopyDiff}>
              {copied ? '✓ Copied' : 'Copy Diff'}
            </button>
            <a
              className="btn-ghost"
              href={`/api/tasks/${encodeURIComponent(selectedTaskId)}/patch`}
              download={`${selectedTaskId}.patch`}
              style={{ textDecoration: 'none' }}
            >
              ⬇ .patch
            </a>
          </div>
        )}
      </div>

      {activeTab === 'diff' && (
        <div className="tab-content">
          {isResolved && diffText && (
            <div className="verified-banner">
              <strong>✅ Fix Verified — All Sandbox Tests Passed!</strong> Below is the exact code patch written by the AI agent. Click <strong>Copy Diff</strong> or <strong>⬇ .patch</strong> above to apply it via <code>git apply</code>, or switch to <strong>Before / After Tests</strong> to compare test runs.
            </div>
          )}
          <div className="diff-window">
            {!diffText ? (
              <div className="empty-state" style={{ marginTop: 28, whiteSpace: 'normal', fontFamily: 'inherit' }}>
                <strong style={{ color: 'var(--text-main)' }}>AI Code Diff Will Appear Here</strong>
                <br />
                Launch a benchmark or custom repo task to see exact red (removed bug) and green (fixed code) lines generated by Groq 120B.
              </div>
            ) : (
              diffText.split('\n').map((line, idx) => {
                let cls = '';
                if (line.startsWith('+') && !line.startsWith('+++')) cls = 'diff-line-add';
                else if (line.startsWith('-') && !line.startsWith('---')) cls = 'diff-line-del';
                else if (line.startsWith('@@') || line.startsWith('---') || line.startsWith('+++')) {
                  cls = 'diff-line-info';
                }
                return (
                  <span key={idx} className={cls}>
                    {line}
                    {'\n'}
                  </span>
                );
              })
            )}
          </div>
        </div>
      )}

      {activeTab === 'terminal' && (
        <div className="tab-content">
          <div className="terminal-window" ref={termRef}>
            {baselineLines.length === 0 && verifyLines.length === 0 ? (
              <div className="empty-state" style={{ marginTop: 28, whiteSpace: 'normal', fontFamily: 'inherit' }}>
                <strong style={{ color: 'var(--text-main)' }}>Isolated Sandbox Test Runner</strong>
                <br />
                Shows <strong>Step 1 (Before Fix)</strong> reproducing the original bug and{' '}
                <strong>Step 2 (After Fix)</strong> proving all tests pass cleanly.
              </div>
            ) : (
              <>
                {baselineLines.length > 0 && (
                  <div className="phase-box phase-box-before">
                    <div className="phase-box-header" onClick={() => setShowBefore((v) => !v)}>
                      <span>
                        {showBefore ? '▼' : '▶'} BEFORE FIX — Step 1: Bug Reproduced (Expected Failures)
                      </span>
                      <span className="phase-box-hint">
                        {showBefore ? 'Click to collapse' : 'Click to inspect original failing tracebacks'}
                      </span>
                    </div>
                    {showBefore && (
                      <div className="phase-box-body">
                        {baselineLines.map((entry, idx) => {
                          const cls = classifyTerminalLine(entry.text);
                          if (!cls) return null;
                          return (
                            <span key={idx} className={cls}>
                              {entry.text}
                            </span>
                          );
                        })}
                      </div>
                    )}
                  </div>
                )}

                {verifyLines.length > 0 && (
                  <div className="phase-box phase-box-after">
                    <div className="phase-box-header">
                      <span>✅ AFTER AI FIX — Step 2: Sandbox Verification Results</span>
                      <span className="phase-box-hint">Post-patch pytest execution</span>
                    </div>
                    <div className="phase-box-body">
                      {verifyLines.map((entry, idx) => {
                        const cls = classifyTerminalLine(entry.text);
                        if (!cls) return null;
                        return (
                          <span key={idx} className={cls}>
                            {entry.text}
                          </span>
                        );
                      })}
                    </div>
                  </div>
                )}
              </>
            )}
          </div>
        </div>
      )}

      {activeTab === 'pr' && (
        <div className="tab-content">
          <div className="pr-card">
            <h3 className="pr-title">{prPayload?.title || 'PR Payload Ready After Verification'}</h3>
            <div className="pr-body">
              {prPayload?.body ||
                'Once the agent verifies all tests pass in the sandbox, a ready-to-submit Pull Request title, changed files summary, and verification log appear here.'}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
